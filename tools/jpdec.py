CT = {'END': '', 'NL': '\n', 'EOM': '¶', 'SP': '　'}


def jp_text(s):
    r = []
    for k, v in msg.tokens(s):
        if k == 't':
            r.append(CT[v])
        elif k == 'f':
            r.append('<%02X>' % v)
        elif k == 'a':
            r.append('{%X:%02X}' % v)
        else:
            i = v - 0x10
            if v < 0x10:
                r.append('{%X}' % v)
            elif i < len(K):
                r.append(K[i])
            else:
                r.append('〔%d〕' % i)
    return ''.join(r)
